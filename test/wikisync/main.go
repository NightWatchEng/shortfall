// Command wikisync regenerates the GitHub wiki page set from docs/ and
// README.md. The wiki is a derived mirror: docs/ in the repository is the
// source of truth (ADR-0008), and the sync workflow (workspace-ehd)
// overwrites wiki-side edits with this tool's output.
//
// Usage: go run ./test/wikisync -repo <repo-root> -out <dir>
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const repoURL = "https://github.com/NightWatchEng/shortfall"

// pageName maps a repo-relative markdown path to its flat wiki page name:
// the docs/ prefix and .md suffix drop, remaining path separators become
// hyphens. README.md at the repo root maps to README.
func pageName(p string) string {
	p = strings.TrimSuffix(p, ".md")
	p = strings.TrimPrefix(p, "docs/")
	return strings.ReplaceAll(p, "/", "-")
}

// notMirrored names directories under docs/ the wiki does not publish.
// docs/internal holds founder- and maintainer-facing records (the go-public
// checklist) that have no reader on a public docs site; mirroring them would
// put project bookkeeping in the same nav as the guides.
var notMirrored = map[string]bool{"docs/internal": true}

// docPages returns repo-relative source path -> wiki page name for every
// mirrored markdown file: README.md plus each .md under docs/, except the
// directories notMirrored names.
func docPages(root string) (map[string]string, error) {
	pages := map[string]string{}
	owner := map[string]string{} // page name -> source path that claimed it
	claim := func(src string) error {
		page := pageName(src)
		if prev, taken := owner[page]; taken {
			return fmt.Errorf("wiki page %q generated by both %s and %s; rename one source", page, prev, src)
		}

		owner[page] = src
		pages[src] = page
		return nil
	}
	if _, err := os.Stat(filepath.Join(root, "README.md")); err == nil {
		if err := claim("README.md"); err != nil {
			return nil, err
		}
	}

	err := filepath.WalkDir(filepath.Join(root, "docs"), func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}

		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}

		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			if notMirrored[rel] {
				return filepath.SkipDir
			}

			return nil
		}

		if !strings.HasSuffix(p, ".md") {
			return nil
		}

		return claim(rel)
	})
	if err != nil {
		return nil, err
	}

	return pages, nil
}

// linkRE matches inline markdown link destinations. Reference-style links
// do not occur in docs/; the sync test set pins the shapes that do.
var linkRE = regexp.MustCompile(`\]\(([^)\s]+)\)`)

// rewriteLine rewrites every relative link destination on one line of the
// source file src (repo-relative), leaving inline code spans (single
// backticks) verbatim. Mirrored .md targets become wiki page names (anchors
// preserved); other repo paths become GitHub blob/tree URLs; absolute URLs
// and pure-anchor links pass through.
func rewriteLine(root, src string, pages map[string]string, line string) string {
	segs := strings.Split(line, "`")
	for i := 0; i < len(segs); i += 2 { // even segments sit outside spans
		segs[i] = rewriteSegment(root, src, pages, segs[i])
	}

	return strings.Join(segs, "`")
}

func rewriteSegment(root, src string, pages map[string]string, seg string) string {
	return linkRE.ReplaceAllStringFunc(seg, func(m string) string {
		dest := m[2 : len(m)-1]
		if strings.Contains(dest, "://") || strings.HasPrefix(dest, "#") || strings.HasPrefix(dest, "mailto:") {
			return m
		}

		target, anchor := dest, ""
		if i := strings.IndexByte(dest, '#'); i >= 0 {
			target, anchor = dest[:i], dest[i:]
		}

		resolved := path.Clean(path.Join(path.Dir(src), target))
		if page, ok := pages[resolved]; ok {
			return "](" + page + anchor + ")"
		}

		info, err := os.Stat(filepath.Join(root, filepath.FromSlash(resolved)))
		if err != nil {
			// Target does not exist in the tree; leave the link as
			// written rather than inventing a destination.
			return m
		}

		kind := "blob"
		if info.IsDir() {
			kind = "tree"
		}

		return "](" + repoURL + "/" + kind + "/main/" + resolved + anchor + ")"
	})
}

// rewriteDoc applies rewriteLine outside fenced code blocks and leaves
// fenced content byte-identical.
func rewriteDoc(root, src string, pages map[string]string, body string) string {
	lines := strings.Split(body, "\n")
	inFence := false
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "```") || strings.HasPrefix(trimmed, "~~~") {
			inFence = !inFence
			continue
		}

		if !inFence {
			lines[i] = rewriteLine(root, src, pages, line)
		}
	}

	return strings.Join(lines, "\n")
}

// navEntry is one curated line of the Home/_Sidebar navigation: the wiki
// page name and the title it is listed under.
type navEntry struct{ page, title string }

// section groups curated pages for navigation in a fixed reading order —
// start here, then reference, then the design record. Order is the whole
// point: a reader arriving at the wiki should be able to follow it top to
// bottom, so this list is maintained by hand rather than sorted.
type section struct {
	title   string
	entries []navEntry
}

